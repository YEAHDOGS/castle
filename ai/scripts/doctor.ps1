# Health check for the whole stack. Exit code 0 = everything required is in place.
. (Join-Path $PSScriptRoot 'common.ps1')
$ErrorActionPreference = 'Continue'
Update-SessionPath
$bad = 0
function Check($name, [scriptblock]$test, $hint) {
  $ok = $false; try { $ok = [bool](& $test) } catch {}
  if ($ok) { Write-Ok $name } else { Write-Warn2 "$name  -> $hint"; $script:bad++ }
}

Write-Step 'Tools'
foreach ($c in 'git', 'node', 'uv', 'ollama', 'opencode') { Check $c { Test-Cmd $c } 'run install.ps1' }
Check 'NVIDIA GPU' { Test-Cmd 'nvidia-smi' } 'install the NVIDIA driver'
if (Test-Cmd 'nvidia-smi') { nvidia-smi --query-gpu=name,memory.used,memory.total --format=csv,noheader | ForEach-Object { "    gpu: $_" } }

Write-Step 'ComfyUI'
Check "checkout at $($Stack.comfyui.ref)" { (git -C $ComfyDir describe --tags 2>$null) -eq $Stack.comfyui.ref } 'run install.ps1'
Check 'venv + CUDA torch' { (& $VenvPy -c "import torch;print(torch.cuda.is_available())" 2>$null) -eq 'True' } 'run install.ps1'
Check 'extra_model_paths.yaml' { Test-Path (Join-Path $Runtime 'extra_model_paths.yaml') } 'run install.ps1'
foreach ($f in $Stack.flux.files) { Check "FLUX file $f" { Test-Path (Join-Path $FluxDir $f) } 'run scripts\download-models.ps1 -OnlyFlux' }
if (Test-Http "$ComfyUrl/system_stats") { Write-Ok "server up at $ComfyUrl" } else { Write-Host "    -- server not running (starts on demand)" }

Write-Step 'Ollama / Qwen'
Check 'ollama server' { Test-Http "$($Stack.ollama.host)/api/version" } 'run scripts\start.ps1'
$models = ollama list 2>$null | Out-String
foreach ($alias in $Stack.ollama.aliases) { Check "model $alias" { $models.Contains($alias) } 'run scripts\download-models.ps1 -OnlyQwen' }

Write-Step 'opencode'
Check "opencode $($Stack.opencode.version)" { (opencode --version 2>$null | Select-Object -Last 1) -eq $Stack.opencode.version } 'run install.ps1'
$cfg = Join-Path $env:USERPROFILE '.config\opencode\opencode.json'
Check 'global config generated by dogs-ai' { Select-String -Path $cfg -Pattern '"\$dogs_ai"' -Quiet } 'run scripts\link-opencode.ps1'
Check 'comfy MCP deps' { Test-Path (Join-Path $Repo 'mcp\comfy-mcp\node_modules\@modelcontextprotocol') } 'run install.ps1'

if ($bad) { Write-Host "`n$bad problem(s) found." -ForegroundColor Yellow; exit 1 } else { Write-Host "`nAll good." -ForegroundColor Green }
